// DEMO-ONLY. Writes src/components/opportunities/official.ts from the review
// manifest produced while choosing each opportunity's official image (6 Oct
// 2026; see docs/AI_HANDOFF.md). Usage:
//   node scripts/opportunity-official-art.js <manifest.json> <image dir>
// Copies the chosen webp files into public/images/opportunities/official.
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const [manifestPath, imgDir] = process.argv.slice(2);
const m = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const out = "public/images/opportunities/official";
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const rows = [];
for (const [id, a] of Object.entries(m).sort()) {
  // A short content hash in the name, so a re-chosen image is never served
  // from a browser or image-optimizer cache of the old one.
  const buf = fs.readFileSync(path.join(imgDir, `${id}.webp`));
  const name = `${id}-${crypto.createHash("sha1").update(buf).digest("hex").slice(0, 6)}.webp`;
  fs.writeFileSync(path.join(out, name), buf);
  rows.push(`  "${id}": { src: "/images/opportunities/official/${name}", fit: "${a.fit}"${a.bg ? `, bg: "${a.bg}"` : ""}, from: ${JSON.stringify(a.from)} },`);
}
const ts = `// DEMO-ONLY: the official image on each opportunity's poster, chosen by
// hand on 6 Oct 2026 (Chandu: "USE OFFICIAL ONES, OFFICIAL LOGOS, OFFICIAL
// GRAPHICS, OFFICIAL MARKETING MATERIAL", then "only good HD ones that are
// meant to be marketing material"). Each is from the provider's own site
// (a press or hero photo, its share image, or its logo); where a site
// refused the request, the institution's logo, shield or building photo as
// published on Wikipedia; the state seal for New Jersey HESAA and New York
// HESC programs (state agencies); Google's logo already in the repo.
// \`fit\` "cover" fills the poster (a photo); "contain" shows the whole
// graphic on \`bg\` (a logo). \`from\` is where each was taken from. These are
// the providers' images: production needs licensed art per provider before
// any public release. Generated by scripts/opportunity-official-art.js; do
// not edit by hand.

export type OfficialArt = { src: string; fit: "cover" | "contain"; bg?: string; from: string };

export const OFFICIAL_ART: Record<string, OfficialArt> = {
${rows.join("\n")}
};
`;
fs.writeFileSync("src/components/opportunities/official.ts", ts);
console.log(rows.length, "images");
