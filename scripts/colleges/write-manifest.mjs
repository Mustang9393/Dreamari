// Writes src/components/colleges/images.ts from what is actually on disk, so
// a card never asks next/image for a file that does not exist.
import { readdirSync, writeFileSync } from "node:fs";
const files = readdirSync("public/images/colleges").filter((f) => f.endsWith(".webp"));
const photos = files.filter((f) => !f.endsWith("-mark.webp")).map((f) => f.replace(".webp", ""));
const marks = files.filter((f) => f.endsWith("-mark.webp")).map((f) => f.replace("-mark.webp", ""));
writeFileSync("src/components/colleges/images.ts", `// Generated by scripts/colleges/write-manifest.mjs. Do not edit.\nexport const PHOTOS = new Set<string>(${JSON.stringify(photos.sort(), null, 2)});\nexport const MARKS = new Set<string>(${JSON.stringify(marks.sort(), null, 2)});\n`);
console.log(photos.length, "photos,", marks.length, "marks");
